// Code 39 uses alternating bar/space elements, with three wide elements per symbol.
const alphabet='0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-. $/+%*';
const patterns=[
  0x034,0x121,0x061,0x160,0x031,0x130,0x070,0x025,0x124,0x064,
  0x109,0x049,0x148,0x019,0x118,0x058,0x00d,0x10c,0x04c,0x01c,
  0x103,0x043,0x142,0x013,0x112,0x052,0x007,0x106,0x046,0x016,
  0x181,0x0c1,0x1c0,0x091,0x190,0x0d0,0x085,0x184,0x0c4,0x0a8,
  0x0a2,0x08a,0x02a,0x094
];
export function code39(value) {
  if (!value || value.length>48 || [...value].some(c=>c==='*'||!alphabet.includes(c))) return null;
  return [...'*'+value+'*'].flatMap((c,index,array)=>{
    const pattern=patterns[alphabet.indexOf(c)];
    const widths=Array.from({length:9},(_,i)=>pattern&(1<<(8-i))?3:1);
    if (index<array.length-1) widths.push(1);
    return widths;
  });
}
